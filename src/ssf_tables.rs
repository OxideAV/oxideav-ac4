/// Convert linear amplitude (Q0.15-ish) to dB×100 using
/// piecewise-linear slope/offset tables ([`SLOPES_LIN_TO_DB`] /
/// [`OFFSETS_LIN_TO_DB`]).
///
/// `idx` selects the linear-amplitude bin (0..50). Returns
/// `slope * x + offset` per Annex C.14, where `x` is the
/// caller-supplied linear delta within the bin.
pub fn lin_to_db(idx: usize, x: i32) -> i32 {
    SLOPES_LIN_TO_DB[idx] * x + OFFSETS_LIN_TO_DB[idx]
}

/// Convert dB to linear amplitude using piecewise-linear
/// slope/offset tables ([`SLOPES_DB_TO_LIN`] /
/// [`OFFSETS_DB_TO_LIN`]).
pub fn db_to_lin(idx: usize, x: i32) -> i32 {
    SLOPES_DB_TO_LIN[idx] * x + OFFSETS_DB_TO_LIN[idx]
}

